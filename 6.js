 //logical operator
// logical operator
// && : if any one is also false output will be false
 console.log(5==5 && 6==5);// false
 console.log(5==5 && 10==10); // true coz both are true.
 console.log(6==4 && 4 == 6);// both are false the ans will be false.

// logical or
// || : if any one is true the output will be true.
console.log(5==5 || 4==3);// true as one value is true.
console.log(4==4 || 2==2);// true as both conditions are true.
console.log(2==0 || 0==2);// false as both the conditions are false.

// logical not
// != : changes the output:  t==>f ; f==>t

console.log(5!==5); //5==5 is true but by adding "!" we will get false.
console.log(4!==6); // the output will be true. 